TestServerHelper::TestServerHelper(const Options& opts) : m_opts(opts) {}

TestServerHelper::~TestServerHelper() {
    stop();
}

bool TestServerHelper::setup() {
    killProcessOnPort(m_opts.clientPort);
    namespace fs = std::filesystem;
    try {
        fs::create_directories(m_opts.workDir);
    } catch (...) {
        std::cerr << "无法创建工作目录: " << m_opts.workDir << "\n";
        return false;
    }
    if (!createTestDataFiles()) return false;
    if (!createServerConfig()) return false;
    return true;
}

void TestServerHelper::killProcessOnPort(int port) {
#ifdef _WIN32
    std::string cmd = "netstat -ano | findstr :" + std::to_string(port) + " | findstr LISTENING";
    FILE* pipe = popen(cmd.c_str(), "r");
    if (!pipe) return;
    char buf[256];
    while (fgets(buf, sizeof(buf), pipe)) {
        std::string line(buf);
        size_t lastNonSpace = line.find_last_not_of(" \t\r\n");
        if (lastNonSpace == std::string::npos) continue;
        size_t lastSpace = line.rfind(' ', lastNonSpace);
        if (lastSpace == std::string::npos) continue;
        std::string pidStr = line.substr(lastSpace + 1, lastNonSpace - lastSpace);
        int pid = std::stoi(pidStr);
        HANDLE h = OpenProcess(PROCESS_TERMINATE, FALSE, pid);
        if (h) {
            TerminateProcess(h, 1);
            WaitForSingleObject(h, 1000);
            CloseHandle(h);
            std::cout << "  已终止残留进程 PID: " << pid << "\n";
        }
    }
    pclose(pipe);
#endif
}


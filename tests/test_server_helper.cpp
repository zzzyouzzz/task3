bool TestServerHelper::start() {
#ifdef _WIN32
    std::string fullPath = std::filesystem::absolute(m_opts.serverPath).string();
    std::string workDirAbs = std::filesystem::absolute(m_opts.workDir).string();

    if (!std::filesystem::exists(fullPath)) {
        std::cerr << "服务器程序不存在: " << fullPath << "\n";
        return false;
    }

    STARTUPINFOA si = { sizeof(si) };
    ZeroMemory(&m_procInfo, sizeof(m_procInfo));

    if (!CreateProcessA(
            fullPath.c_str(), NULL,
            NULL, NULL, FALSE,
            CREATE_NO_WINDOW,
            NULL, workDirAbs.c_str(),
            &si, &m_procInfo)) {
        std::cerr << "CreateProcess failed (" << GetLastError() << "): " << fullPath << "\n";
        return false;
    }
    m_serverRunning = true;
    std::cout << "服务器进程已启动 (PID: " << m_procInfo.dwProcessId << ")\n";
    return true;
#else
    std::cerr << "仅支持 Windows\n";
    return false;
#endif
}

void TestServerHelper::stop() {
#ifdef _WIN32
    if (m_serverRunning && m_procInfo.hProcess) {
        DWORD exitCode = 0;
        if (GetExitCodeProcess(m_procInfo.hProcess, &exitCode) && exitCode == STILL_ACTIVE) {
            TerminateProcess(m_procInfo.hProcess, 0);
            WaitForSingleObject(m_procInfo.hProcess, 3000);
        }
        CloseHandle(m_procInfo.hProcess);
        CloseHandle(m_procInfo.hThread);
        ZeroMemory(&m_procInfo, sizeof(m_procInfo));
        m_serverRunning = false;
        std::cout << "服务器进程已停止\n";
    }
#endif
}

bool TestServerHelper::waitForReady(int maxRetries, int delayMs) {
    std::cout << "等待服务器就绪...\n";
    for (int i = 0; i < maxRetries; ++i) {
#ifdef _WIN32
        WSADATA wsaData;
        bool wsaStarted = (WSAStartup(MAKEWORD(2, 2), &wsaData) == 0);
        SOCKET s = socket(AF_INET, SOCK_STREAM, 0);
        if (s != INVALID_SOCKET) {
            sockaddr_in addr;
            addr.sin_family = AF_INET;
            addr.sin_port = htons(m_opts.clientPort);
            addr.sin_addr.s_addr = inet_addr(m_opts.clientIp.c_str());
            if (connect(s, (sockaddr*)&addr, sizeof(addr)) != SOCKET_ERROR) {
                closesocket(s);
                if (wsaStarted) WSACleanup();
                std::cout << "服务器就绪 (尝试 " << (i + 1) << " 次)\n";
                return true;
            }
            closesocket(s);
        }
        if (wsaStarted) WSACleanup();
#endif
        std::this_thread::sleep_for(std::chrono::milliseconds(delayMs));
    }
    std::cerr << "服务器未能就绪 (超时)\n";
    return false;
}

void TestServerHelper::cleanup() {
    namespace fs = std::filesystem;
    try {
        if (fs::exists(m_opts.workDir)) {
            fs::remove_all(m_opts.workDir);
        }
    } catch (...) {}
}

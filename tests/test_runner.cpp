void TestRunner::killProcessOnPort(int port) {
#ifdef _WIN32
    // 使用 netstat 查找占用端口的 PID 并终止
    std::string cmd = "netstat -ano | findstr :" + std::to_string(port) + " | findstr LISTENING";
    FILE* pipe = popen(cmd.c_str(), "r");
    if (!pipe) return;
    char buf[256];
    while (fgets(buf, sizeof(buf), pipe)) {
        std::string line(buf);
        // 提取最后一列 PID
        size_t lastNonSpace = line.find_last_not_of(" \t\r\n");
        if (lastNonSpace == std::string::npos) continue;
        size_t lastSpace = line.rfind(' ', lastNonSpace);
        if (lastSpace == std::string::npos) continue;
        std::string pidStr = line.substr(lastSpace + 1, lastNonSpace - lastSpace);
        int pid = std::stoi(pidStr);
        HANDLE h = OpenProcess(PROCESS_TERMINATE, FALSE, pid);
        if (h) {
            TerminateProcess(h, 1);
            WaitForSingleObject(h, 1000);
            CloseHandle(h);
            std::cout << "  已终止残留进程 PID: " << pid << "\n";
        }
    }
    pclose(pipe);
#endif
}

bool TestRunner::startServer() {
#ifdef _WIN32
    // 先清理占用端口的残留进程
    killProcessOnPort(m_opts.clientPort);

    std::string fullPath = std::filesystem::absolute(m_opts.serverPath).string();
    std::string workDirAbs = std::filesystem::absolute(m_opts.workDir).string();

    if (!std::filesystem::exists(fullPath)) {
        std::cerr << "服务器程序不存在: " << fullPath << "\n";
        return false;
    }

    STARTUPINFOA si = { sizeof(si) };
    ZeroMemory(&m_serverProcInfo, sizeof(m_serverProcInfo));

    BOOL ok = CreateProcessA(
        fullPath.c_str(),
        NULL,
        NULL, NULL,
        FALSE,
        CREATE_NO_WINDOW,
        NULL,
        workDirAbs.c_str(),
        &si,
        &m_serverProcInfo
    );

    if (!ok) {
        std::cerr << "CreateProcess failed (" << GetLastError() << "): " << fullPath << "\n";
        return false;
    }
    m_serverRunning = true;
    std::cout << "服务器进程已启动 (PID: " << m_serverProcInfo.dwProcessId << ")\n";
    return true;
#else
    std::cerr << "仅支持 Windows\n";
    return false;
#endif
}

void TestRunner::stopServer() {
#ifdef _WIN32
    if (m_serverRunning && m_serverProcInfo.hProcess) {
        // 检查进程是否还活着
        DWORD exitCode = 0;
        if (GetExitCodeProcess(m_serverProcInfo.hProcess, &exitCode) && exitCode == STILL_ACTIVE) {
            TerminateProcess(m_serverProcInfo.hProcess, 0);
            WaitForSingleObject(m_serverProcInfo.hProcess, 3000);
        }
        CloseHandle(m_serverProcInfo.hProcess);
        CloseHandle(m_serverProcInfo.hThread);
        ZeroMemory(&m_serverProcInfo, sizeof(m_serverProcInfo));
        m_serverRunning = false;
        std::cout << "服务器进程已停止\n";
    }
#endif
}

bool TestRunner::waitForServerReady(int maxRetries, int delayMs) {
    std::cout << "等待服务器就绪...\n";
    for (int i = 0; i < maxRetries; ++i) {
        // 检查服务器进程是否还活着
#ifdef _WIN32
        DWORD exitCode = 0;
        if (m_serverRunning && m_serverProcInfo.hProcess) {
            GetExitCodeProcess(m_serverProcInfo.hProcess, &exitCode);
            if (exitCode != STILL_ACTIVE) {
                std::cerr << "  服务器进程已退出 (code=" << exitCode << ")\n";
                return false;
            }
        }
#endif
        // 尝试连接端口
#ifdef _WIN32
        WSADATA wsaData;
        bool wsaStarted = (WSAStartup(MAKEWORD(2,2), &wsaData) == 0);
        SOCKET s = socket(AF_INET, SOCK_STREAM, 0);
        if (s != INVALID_SOCKET) {
            sockaddr_in addr;
            addr.sin_family = AF_INET;
            addr.sin_port = htons(m_opts.clientPort);
            addr.sin_addr.s_addr = inet_addr(m_opts.clientIp.c_str());
            if (connect(s, (sockaddr*)&addr, sizeof(addr)) != SOCKET_ERROR) {
                closesocket(s);
                if (wsaStarted) WSACleanup();
                std::cout << "服务器就绪 (尝试 " << (i + 1) << " 次)\n";
                return true;
            }
            closesocket(s);
        }
        if (wsaStarted) WSACleanup();
#endif
        std::this_thread::sleep_for(std::chrono::milliseconds(delayMs));
    }
    std::cerr << "  服务器未能就绪 (超时)\n";
    return false;
}

// ======================== .in 文件处理 ========================

bool TestRunner::processFile() {
    std::ifstream file(m_opts.inputFile);
    if (!file) {
        std::cerr << "无法打开输入文件: " << m_opts.inputFile << "\n";
        return false;
    }

    std::string line;
    int lineNum = 0;
    int passed = 0, failed = 0;

    while (std::getline(file, line)) {
        ++lineNum;
        // 去除行首尾空白
        size_t start = line.find_first_not_of(" \t\r\n");
        if (start == std::string::npos) continue;
        line = line.substr(start);
        // 去除末尾空白
        size_t end = line.find_last_not_of(" \t\r\n");
        if (end != std::string::npos) line = line.substr(0, end + 1);

        // 跳过空行和注释
        if (line.empty() || line[0] == '#') continue;

        if (!executeCommand(line, lineNum)) {
            ++m_failedTests;
        } else {
            ++m_passedTests;
        }
        ++m_totalTests;
    }

    return m_failedTests == 0;
}

bool TestRunner::executeCommand(const std::string& line, int lineNum) {
    std::vector<std::string> tokens = split(line, '|');
    if (tokens.empty()) return true;

    std::string cmd = tokens[0];
    std::vector<std::string> args(tokens.begin() + 1, tokens.end());

    // 替换 PCL* 通配符
    for (auto& arg : args) {
        if (arg == "PCL*" && !m_lastParcelId.empty()) {
            arg = m_lastParcelId;
        }
    }

    if (cmd == "REGISTER")        return cmdRegister(args);
    else if (cmd == "LOGIN")      return cmdLogin(args);
    else if (cmd == "SEND")       return cmdSend(args);
    else if (cmd == "ASSIGN")     return cmdAssign(args);
    else if (cmd == "COLLECT")    return cmdCollect(args);
    else if (cmd == "SIGN")       return cmdSign(args);
    else if (cmd == "RECHARGE")   return cmdRecharge(args);
    else if (cmd == "CHANGE_PWD") return cmdChangePwd(args);
    else if (cmd == "QUERY_PARCELS") return cmdQueryParcels(args);
    else if (cmd == "QUERY_USERS")   return cmdQueryUsers(args);
    else if (cmd == "QUERY_BALANCE") return cmdQueryBalance(args);
    else if (cmd == "DELETE_USER")   return cmdDeleteUser(args);
    else if (cmd == "DELETE_PARCEL") return cmdDeleteParcel(args);
    else if (cmd == "GET_STATS")     return cmdGetStats(args);
    else if (cmd == "LOGOUT")        return cmdLogout(args);
    else if (cmd == "WAIT")          return cmdWait(args);
    else if (cmd == "CHECK_FILE")    return cmdCheckFile(args);
    else if (cmd == "CHECK_BALANCE") return cmdCheckBalance(args);
    else if (cmd == "PRINT")         return cmdPrint(args);
    else {
        report(false, "未知命令: " + cmd, lineNum);
        return false;
    }
}


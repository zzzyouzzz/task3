// ======================== main ========================
int main(int argc, char* argv[]) {
    g_logger.initialize("test_runner.log", LOG_FATAL, false);

    TestRunner::Options opts;
    opts.serverPath = "output/server/server.exe";
    opts.workDir = "output/test_run";

    for (int i = 1; i < argc; ++i) {
        std::string arg = argv[i];
        auto eq = arg.find('=');
        if (eq == std::string::npos) continue;
        std::string key = arg.substr(0, eq);
        std::string val = arg.substr(eq + 1);
        if (key == "--input") opts.inputFile = val;
        else if (key == "--server") opts.serverPath = val;
        else if (key == "--workdir") opts.workDir = val;
        else if (key == "--ip") opts.clientIp = val;
        else if (key == "--port") opts.clientPort = std::stoi(val);
    }

    if (opts.inputFile.empty()) {
        std::cerr << "Usage: IntegrationTest --input=<scenario.in> [--server=<server.exe>] [--workdir=<dir>]\n";
        return 1;
    }

    TestRunner runner(opts);
    return runner.run();
}

// ======================== TestRunner ========================

TestRunner::TestRunner(const Options& opts) : m_opts(opts) {}
TestRunner::~TestRunner() { stopServer(); }

int TestRunner::run() {
    std::cout << "\n========================================\n";
    std::cout << "  全流程自动化测试开始\n";
    std::cout << "========================================\n\n";

    if (!setupTestEnvironment()) {
        std::cerr << "FAIL: 测试环境初始化失败\n";
        cleanupTestEnvironment();
        return 1;
    }
    if (!startServer()) {
        std::cerr << "FAIL: 服务器启动失败\n";
        cleanupTestEnvironment();
        return 1;
    }
    if (!waitForServerReady()) {
        std::cerr << "FAIL: 服务器未就绪\n";
        stopServer();
        cleanupTestEnvironment();
        return 1;
    }
    if (!m_comm.connectToServer(m_opts.clientIp, m_opts.clientPort)) {
        std::cerr << "FAIL: 无法连接到服务器\n";
        stopServer();
        cleanupTestEnvironment();
        return 1;
    }

    std::cout << "服务器已连接，开始执行测试脚本: " << m_opts.inputFile << "\n\n";

    bool allPassed = processFile();

    m_comm.disconnect();
    stopServer();
    cleanupTestEnvironment();

    std::cout << "\n========================================\n";
    std::cout << "  测试结果汇总\n";
    std::cout << "  总计: " << m_totalTests << "\n";
    std::cout << "  通过: " << m_passedTests << "\n";
    std::cout << "  失败: " << m_failedTests << "\n";
    std::cout << "========================================\n\n";

    return allPassed ? 0 : 1;
}


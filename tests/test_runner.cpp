std::vector<std::string> TestRunner::split(const std::string& str, char delim) {
    std::vector<std::string> tokens;
    std::istringstream iss(str);
    std::string token;
    while (std::getline(iss, token, delim)) {
        tokens.push_back(token);
    }
    return tokens;
}

std::string TestRunner::resolveParcelId(const std::string& raw) {
    if (raw == "PCL*" && !m_lastParcelId.empty()) return m_lastParcelId;
    return raw;
}

ErrorCode TestRunner::parseErrorCode(const std::string& str) {
    if (str == "SUCCESS")               return ErrorCode::SUCCESS;
    if (str == "INVALID_ARGS")          return ErrorCode::INVALID_ARGS;
    if (str == "PERMISSION_DENIED")     return ErrorCode::PERMISSION_DENIED;
    if (str == "NOT_LOGGED_IN")         return ErrorCode::NOT_LOGGED_IN;
    if (str == "USER_NOT_FOUND")        return ErrorCode::USER_NOT_FOUND;
    if (str == "USER_EXISTS")           return ErrorCode::USER_EXISTS;
    if (str == "INSUFFICIENT_BALANCE")  return ErrorCode::INSUFFICIENT_BALANCE;
    if (str == "PARCEL_NOT_FOUND")      return ErrorCode::PARCEL_NOT_FOUND;
    if (str == "INVALID_STATUS")        return ErrorCode::INVALID_STATUS;
    if (str == "LOGIN_FAILED")          return ErrorCode::LOGIN_FAILED;
    if (str == "INVALID_AMOUNT")        return ErrorCode::INVALID_AMOUNT;
    if (str == "COURIER_BUSY")          return ErrorCode::COURIER_BUSY;
    if (str == "NO_RESULT")             return ErrorCode::NO_RESULT;
    if (str == "DELETE_BLOCKED")        return ErrorCode::DELETE_BLOCKED;
    if (str == "PARCEL_STATUS_INVALID") return ErrorCode::PARCEL_STATUS_INVALID;
    if (str == "USER_NOT_LOGIN")        return ErrorCode::USER_NOT_LOGIN;
    if (str == "USER_ALREADY_LOGIN")    return ErrorCode::USER_ALREADY_LOGIN;
    if (str == "INTERNAL_ERROR")        return ErrorCode::INTERNAL_ERROR;
    return ErrorCode::UNKNOWN;
}

std::string TestRunner::errorCodeToString(ErrorCode ec) {
    switch (ec) {
        case ErrorCode::SUCCESS:              return "SUCCESS";
        case ErrorCode::INVALID_ARGS:         return "INVALID_ARGS";
        case ErrorCode::PERMISSION_DENIED:    return "PERMISSION_DENIED";
        case ErrorCode::NOT_LOGGED_IN:        return "NOT_LOGGED_IN";
        case ErrorCode::USER_NOT_FOUND:       return "USER_NOT_FOUND";
        case ErrorCode::USER_EXISTS:          return "USER_EXISTS";
        case ErrorCode::INSUFFICIENT_BALANCE: return "INSUFFICIENT_BALANCE";
        case ErrorCode::PARCEL_NOT_FOUND:     return "PARCEL_NOT_FOUND";
        case ErrorCode::INVALID_STATUS:       return "INVALID_STATUS";
        case ErrorCode::LOGIN_FAILED:         return "LOGIN_FAILED";
        case ErrorCode::INVALID_AMOUNT:       return "INVALID_AMOUNT";
        case ErrorCode::COURIER_BUSY:         return "COURIER_BUSY";
        case ErrorCode::NO_RESULT:            return "NO_RESULT";
        case ErrorCode::DELETE_BLOCKED:       return "DELETE_BLOCKED";
        case ErrorCode::PARCEL_STATUS_INVALID:return "PARCEL_STATUS_INVALID";
        case ErrorCode::USER_NOT_LOGIN:       return "USER_NOT_LOGIN";
        case ErrorCode::USER_ALREADY_LOGIN:   return "USER_ALREADY_LOGIN";
        case ErrorCode::INTERNAL_ERROR:       return "INTERNAL_ERROR";
        default:                              return "UNKNOWN(" + std::to_string(static_cast<int>(ec)) + ")";
    }
}

bool TestRunner::expectErrorCode(ErrorCode actual, const std::string& expectedStr) {
    ErrorCode expected = parseErrorCode(expectedStr);
    if (actual != expected) {
        std::cout << "  [FAIL] 期望 " << expectedStr << " (" << errorCodeToString(expected)
                  << "), 实际 " << errorCodeToString(actual) << "\n";
        return false;
    }
    return true;
}

bool TestRunner::expectInt(int actual, const std::string& expectedStr) {
    int expected = std::stoi(expectedStr);
    if (actual != expected) {
        std::cout << "  [FAIL] 期望 " << expected << ", 实际 " << actual << "\n";
        return false;
    }
    return true;
}

bool TestRunner::expectDouble(double actual, const std::string& expectedStr) {
    double expected = std::stod(expectedStr);
    if (std::abs(actual - expected) >= 0.001) {
        std::cout << "  [FAIL] 期望 " << expected << ", 实际 " << actual << "\n";
        return false;
    }
    return true;
}

void TestRunner::report(bool passed, const std::string& desc, int lineNum) {
    if (passed) {
        std::cout << "  [PASS] " << desc << "\n";
    } else {
        std::cout << "  [FAIL] " << desc;
        if (lineNum > 0) std::cout << " (行 " << lineNum << ")";
        std::cout << "\n";
    }
}
